-- Q4.1
SELECT (LO_ORDERDATE / 10000) AS YEAR, C_NATION, SUM(LO_REVENUE - LO_SUPPLYCOST) AS profit 
FROM lineorder_flat 
WHERE C_REGION = 'AMERICA' AND S_REGION = 'AMERICA' 
  AND (P_MFGR = 'MFGR#1' OR P_MFGR = 'MFGR#2') 
GROUP BY YEAR, C_NATION ORDER BY YEAR, C_NATION;

-- Q4.2
SELECT (LO_ORDERDATE / 10000) AS YEAR, S_NATION, P_CATEGORY, SUM(LO_REVENUE - LO_SUPPLYCOST) AS profit 
FROM lineorder_flat 
WHERE C_REGION = 'AMERICA' AND S_REGION = 'AMERICA' 
  AND (LO_ORDERDATE / 10000 = 1997 OR LO_ORDERDATE / 10000 = 1998) 
  AND (P_MFGR = 'MFGR#1' OR P_MFGR = 'MFGR#2') 
GROUP BY YEAR, S_NATION, P_CATEGORY ORDER BY YEAR, S_NATION, P_CATEGORY;

-- Q4.3
SELECT (LO_ORDERDATE / 10000) AS YEAR, S_CITY, P_BRAND, SUM(LO_REVENUE - LO_SUPPLYCOST) AS profit 
FROM lineorder_flat 
WHERE S_NATION = 'UNITED STATES' 
  AND (LO_ORDERDATE / 10000 = 1997 OR LO_ORDERDATE / 10000 = 1998) 
  AND P_CATEGORY = 'MFGR#14' 
GROUP BY YEAR, S_CITY, P_BRAND ORDER BY YEAR, S_CITY, P_BRAND;

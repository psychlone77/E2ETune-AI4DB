FROM lineorder_flat 
WHERE C_REGION = 'ASIA' AND S_REGION = 'ASIA' 
  AND LO_ORDERDATE >= 19920101 AND LO_ORDERDATE <= 19971231 
GROUP BY YEAR, C_NATION, S_NATION ORDER BY YEAR ASC, revenue DESC;

